pub(super) fn encode_jpg(input: &[u8]) -> Result<Option<Pcf2Segment>> {
  if input.len() < 4 || input[0] != 0xFF || input[1] != 0xD8 {
    return Ok(None);
  }
  let mut mjpg_used = false;
  let mut jpeg = input.to_vec();
  let lepton = if jpeg_has_dht(&jpeg) {
    encode_lepton(&jpeg)
  } else {
    match encode_lepton(&jpeg) {
      Ok(v) => Ok(v),
      Err(_) => {
        let mut with_dht = jpeg.clone();
        if !insert_mjpg_dht(&mut with_dht) {
          return Ok(None);
        }
        mjpg_used = true;
        jpeg = with_dht;
        encode_lepton(&jpeg)
      }
    }
  };
  let lepton = match lepton {
    Ok(v) => v,
    Err(_) => return Ok(None),
  };
  // lepton normalizes some non-canonical inputs (e.g. a missing EOI marker), so
  // only keep the segment when decoding reproduces the stored bytes exactly.
  let restored = match decode_lepton(&lepton) {
    Ok(v) => v,
    Err(_) => return Ok(None),
  };
  if restored != jpeg {
    return Ok(None);
  }
  let mut meta = Vec::with_capacity(2);
  meta.push(1);
  meta.push(if mjpg_used { 1 } else { 0 });
  Ok(Some(Pcf2Segment {
    kind: SegmentKind::Jpg as u8,
    flags: 0,
    orig_len: input.len() as u64,
    meta,
    data: lepton,
  }))
}

pub(super) fn jpeg_has_dht(jpeg: &[u8]) -> bool {
  if jpeg.len() < 4 || jpeg[0] != 0xFF || jpeg[1] != 0xD8 {
    return false;
  }
  let mut pos = 2usize;
  while pos + 1 < jpeg.len() {
    if jpeg[pos] != 0xFF {
      pos += 1;
      continue;
    }
    while pos < jpeg.len() && jpeg[pos] == 0xFF {
      pos += 1;
    }
    if pos >= jpeg.len() {
      break;
    }
    let marker = jpeg[pos];
    pos += 1;
    if marker == 0xD9 || marker == 0xDA {
      break;
    }
    if marker == 0xD8 || marker == 0x01 || (0xD0..=0xD7).contains(&marker) {
      continue;
    }
    if pos + 1 >= jpeg.len() {
      break;
    }
    let len = u16::from_be_bytes([jpeg[pos], jpeg[pos + 1]]) as usize;
    if len < 2 || pos + len > jpeg.len() {
      break;
    }
    if marker == 0xC4 {
      return true;
    }
    pos += len;
  }
  false
}

fn insert_mjpg_dht(jpeg: &mut Vec<u8>) -> bool {
  if jpeg.len() < 4 || jpeg[0] != 0xFF || jpeg[1] != 0xD8 {
    return false;
  }
  let mut found_ff = false;
  let mut found_ffda = false;
  let mut ffda_pos: isize = -1;
  loop {
    ffda_pos += 1;
    if ffda_pos as usize >= jpeg.len() {
      break;
    }
    let byte = jpeg[ffda_pos as usize];
    if found_ff {
      found_ffda = byte == 0xDA;
      if found_ffda {
        break;
      }
      found_ff = false;
    } else {
      found_ff = byte == 0xFF;
    }
  }
  if !found_ffda {
    return false;
  }
  let insert_pos = ffda_pos - 1;
  if insert_pos < 0 {
    return false;
  }
  let insert_pos = insert_pos as usize;
  jpeg.splice(insert_pos..insert_pos, MJPGDHT);
  true
}

fn remove_mjpg_dht(jpeg: &mut Vec<u8>) -> bool {
  if jpeg.len() < MJPGDHT_LEN + 4 || jpeg[0] != 0xFF || jpeg[1] != 0xD8 {
    return false;
  }
  let mut found_ff = false;
  let mut found_ffda = false;
  let mut ffda_pos: isize = -1;
  loop {
    ffda_pos += 1;
    if ffda_pos as usize >= jpeg.len() {
      break;
    }
    let byte = jpeg[ffda_pos as usize];
    if found_ff {
      found_ffda = byte == 0xDA;
      if found_ffda {
        break;
      }
      found_ff = false;
    } else {
      found_ff = byte == 0xFF;
    }
  }
  if !found_ffda {
    return false;
  }
  let insert_pos = ffda_pos - 1;
  if insert_pos < MJPGDHT_LEN as isize {
    return false;
  }
  let insert_pos = insert_pos as usize;
  let start = insert_pos - MJPGDHT_LEN;
  if jpeg.get(start..insert_pos) == Some(&MJPGDHT[..]) {
    jpeg.drain(start..insert_pos);
    return true;
  }
  false
}

fn encode_lepton(jpeg: &[u8]) -> Result<Vec<u8>> {
  let mut reader = Cursor::new(jpeg);
  let mut writer = Cursor::new(Vec::new());
  let features = lepton_jpeg::EnabledFeatures::compat_lepton_vector_write();
  lepton_jpeg::encode_lepton(&mut reader, &mut writer, &features, &lepton_jpeg::DEFAULT_THREAD_POOL)
    .map_err(|err| Error::Other(format!("lepton encode failed: {err}")))?;
  Ok(writer.into_inner())
}

fn decode_lepton(data: &[u8]) -> Result<Vec<u8>> {
  let mut reader = Cursor::new(data);
  let mut out = Vec::new();
  let features = lepton_jpeg::EnabledFeatures::compat_lepton_vector_read();
  lepton_jpeg::decode_lepton(&mut reader, &mut out, &features, &lepton_jpeg::DEFAULT_THREAD_POOL)
    .map_err(|err| Error::Other(format!("lepton decode failed: {err}")))?;
  Ok(out)
}

pub(super) fn decode_jpg_segment(segment: &Pcf2Segment, budget: &mut DecodeBudget, config: &DecodeConfig) -> Result<Vec<u8>> {
  if segment.meta.len() < 2 {
    return Err(Error::InvalidSegment("jpg meta"));
  }
  let meta_version = segment.meta[0];
  if meta_version != 1 {
    return Err(Error::InvalidSegment("jpg meta_version"));
  }
  let mjpg_used = segment.meta[1] != 0;
  let mut jpeg = decode_lepton(&segment.data)?;
  if mjpg_used && !remove_mjpg_dht(&mut jpeg) {
    return Err(Error::InvalidSegment("jpg mjpg dht"));
  }
  budget.consume(jpeg.len(), config)?;
  Ok(jpeg)
}
